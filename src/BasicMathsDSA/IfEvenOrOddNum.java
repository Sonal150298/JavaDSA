package src.BasicMathsDSA;

public class IfEvenOrOddNum {
    public static void main(String[] args) {
        int n=987654321;

        if(n!=0)
        {
            if(n%2==0)
                System.out.println("Number is Even");
            else
                System.out.println("Number is Odd");
        }

    }
}
